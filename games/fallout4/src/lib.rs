pub(crate) use rsf_game_sys::win32::{Plain, read};

/// Guarded read of `address` into `into`, left unchanged when the read fails.
pub(crate) fn load<T: Plain>(address: usize, into: &mut T) -> bool {
    read(address).map(|value| *into = value).is_some()
}

/// The guarded image bytes at `rva` equal `expected`. Startup verification only.
pub(crate) fn guard(rva: usize, expected: &[u8]) -> bool {
    let mut actual = vec![0u8; expected.len()];
    (unsafe {
        rsf_game_sys::win32::read_process(
            image().wrapping_add(rva),
            actual.as_mut_ptr().cast(),
            actual.len(),
        )
    }) && actual == expected
}

/// Float arrays compared by bit pattern.
pub(crate) fn bits<const N: usize>(values: &[f32; N]) -> [u32; N] {
    values.map(f32::to_bits)
}

/// Two canonical identities of live objects name the same object.
pub(crate) fn same_object(a: u64, b: u64) -> bool {
    a != 0 && b != 0 && a == b
}

pub(crate) fn image() -> usize {
    unsafe { GetModuleHandleW(std::ptr::null()) as usize }
}

/// Pins the module that contains `address` for the process.
pub(crate) fn pin(address: *const c_void) -> bool {
    rsf_game_sys::win32::pin_module(address).is_some()
}

/// A terminated C string for the host log.
pub(crate) fn message(text: String) -> CString {
    let mut bytes = text.into_bytes();
    bytes.retain(|&byte| byte != 0);
    // SAFETY: retain removed every interior NUL.
    unsafe { CString::from_vec_unchecked(bytes) }
}

unsafe extern "C" fn detect(probe: *const rsf_game_probe) -> rsf_detection {
    unsafe { Probe::detect(probe, |probe| probe.matches(EXECUTABLE, EXECUTABLE_SHA256)) }
}

/// Publishes the exported Fallout 4 GameSDK table.
///
/// # Safety
/// The output points to a caller-owned plugin table.
#[unsafe(no_mangle)]
unsafe extern "C" fn rsf_get_game_plugin_api(
    requested_abi: u32,
    out: *mut rsf_game_plugin_api,
) -> rsf_result {
    let info = rsf_game_info {
        id: c"fallout4".as_ptr(),
        name: c"Fallout 4".as_ptr(),
        version: VERSION.as_ptr().cast(),
        rendering_ready: 0,
        status: PENDING.as_ptr(),
    };
    let hooks = rsf_game_hooks_api {
        prepare: Some(session::prepare),
        start: Some(session::start),
        quiesce: Some(session::quiesce),
        stop: Some(session::stop),
        status: Some(session::status),
    };
    unsafe { publish_api(requested_abi, out, info, detect, hooks) }
}
