#!/usr/bin/env python3
"""Generate both sides of the append-only NativeBridge.status array."""

import argparse
from pathlib import Path

MOD = Path(__file__).resolve().parents[1]
MINIMUM = 14
# Each getter and its Rust value share one slot. Older callers retain their original prefix.
FIELDS = [
    ("requestedSr", "i64::from(status.requested_sr)"),
    ("effectiveSr", "i64::from(status.effective_sr)"),
    ("requestedFg", "i64::from(status.requested_fg)"),
    ("effectiveFg", "i64::from(status.effective_fg)"),
    ("srResult", "i64::from(status.sr_result)"),
    ("fgSwitchResult", "i64::from(status.fg_switch_result)"),
    ("evaluated", "status.evaluated as i64"),
    ("fgReason", "i64::from(fg.reason)"),
    ("fgResult", "i64::from(fg.last_result)"),
    ("effectiveGeneratedFrames", "i64::from(vendor.effective_generated_frames)"),
    ("taggedFrames", "fg.tagged_frames as i64"),
    ("generatedPresented", "vendor.generated_presented as i64"),
    ("fgActive", "i64::from(vendor.active)"),
    ("fgValidStatistics", "i64::from(vendor.valid_statistics)"),
    ("maxGeneratedFrames", "i64::from(vendor.max_generated_frames)"),
    ("fgSupported", "i64::from(vendor.supported)"),
    ("latencyOwner", "i64::from(latency.owner)"),
    ("pacedFrames", "latency.paced_frames as i64"),
    ("keyboardEvents", "events.input_events[0] as i64"),
    ("mouseEvents", "events.input_events[1] as i64"),
    ("controllerEvents", "events.input_events[2] as i64"),
    ("pings", "events.pings as i64"),
    ("substitutes", "events.substitutes as i64"),
    ("orderViolations", "events.order_violations as i64"),
    ("derivedBoundaries", "latency.derived_boundaries as i64"),
    ("latencyAvailable", "i64::from(latency_available)"),
]

RUST = """// SPDX-License-Identifier: MIT
// Generated by eng/generate-native-status.py.

use crate::platform_abi::{rsf_gl_pipeline_status, rsf_native_latency_status};

pub(crate) const STATUS_MINIMUM: usize = @MINIMUM@;

pub(crate) fn status_values(
    status: &rsf_gl_pipeline_status,
    latency: Option<&rsf_native_latency_status>,
) -> [i64; @COUNT@] {
    let fg = &status.generation;
    let vendor = &fg.vendor;
    let latency_available = latency.is_some();
    let unavailable = rsf_native_latency_status::default();
    let latency = latency.unwrap_or(&unavailable);
    let events = &latency.events;
    [
@VALUES@
    ]
}
"""

JAVA = """// SPDX-License-Identifier: MIT
// Generated by eng/generate-native-status.py.

package org.kpc.rescaleframecraft.render;

final class NativeStatus {
    static final int COUNT = @COUNT@;

    private NativeStatus() {}

    private static long get(long[] values, int index) {
        return index < values.length ? values[index] : 0;
    }
@GETTERS@
}
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    rust = RUST.replace("@MINIMUM@", str(MINIMUM)).replace("@COUNT@", str(len(FIELDS)))
    rust = rust.replace("@VALUES@", "\n".join(f"        {expr}," for _, expr in FIELDS))
    getters = "\n".join(
        f"    static long {name}(long[] values) {{ return get(values, {index}); }}"
        for index, (name, _) in enumerate(FIELDS)
    )
    java = JAVA.replace("@COUNT@", str(len(FIELDS))).replace("@GETTERS@", getters)
    outputs = (
        (MOD / "native/status.rs", rust),
        (MOD / "src/main/java/org/kpc/rescaleframecraft/render/NativeStatus.java", java),
    )
    for path, content in outputs:
        if args.check:
            if not path.exists() or path.read_bytes() != content.encode("utf-8"):
                parser.error(f"regenerate {path}")
        else:
            path.write_text(content, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
