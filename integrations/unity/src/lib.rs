//! The Unity package and render bridge: settings and status, session state, SR views,
//! presentation, the D3D11, D3D12 and Vulkan bridges, generation setup and the Editor preview,
//! linked into `ReScaleFrame.Unity.Native.dll`. The Mono plugin (`games/unity-mono`) builds the
//! `mono-plugin` subset (its D3D12 callbacks and the shared frame state) into its own DLL.
#![cfg(any(windows, test))]
// The unit-test build leaves out the native bridges that call most of the state modules.
#![cfg_attr(test, allow(dead_code))]

// The plugins get the Runtime from CMake; unit tests link the crate.
#[cfg(all(test, windows))]
use rsf_orchestrator as _;
#[cfg(all(test, windows))]
use rsf_runtime_common as _;

/// C bindings of the Unity bridge and package headers (generated by build.rs), re-exported with
/// the public SDK ones.
#[allow(
    non_camel_case_types,
    non_upper_case_globals,
    non_snake_case,
    dead_code,
    clippy::all
)]
pub mod sys {
    pub use rsf_game_sys::*;
    include!(concat!(env!("OUT_DIR"), "/sys.rs"));
}

#[cfg(all(windows, not(test)))]
mod bridge_d3d12;
#[cfg(any(test, not(feature = "mono-plugin")))]
mod bridge_interop;
// Unity SDK dispatch over the C leaves in native/render_bridge.c, which need the untracked Unity
// native headers; unit tests cover the packet state and policy it drives.
#[cfg(all(windows, not(test)))]
mod bridge_native;
pub mod bridge_state;
mod d3d11_pass;
#[cfg(any(test, not(feature = "mono-plugin")))]
mod d3d11_state;
#[cfg(any(test, not(feature = "mono-plugin")))]
mod device_creation;
pub mod generation;
#[cfg(any(test, not(feature = "mono-plugin")))]
mod package_state;
#[cfg(any(test, not(feature = "mono-plugin")))]
mod package_views;
#[cfg(all(windows, not(feature = "mono-plugin")))]
mod preview;
pub mod runtime_config;
#[cfg(all(windows, not(feature = "mono-plugin"), not(test)))]
mod vulkan_platform;
#[cfg(any(test, not(feature = "mono-plugin")))]
mod vulkan_resolver;
#[cfg(any(test, not(feature = "mono-plugin")))]
mod vulkan_state;
