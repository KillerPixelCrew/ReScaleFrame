"""Regenerate embedded SPIR-V from the same raw-string HLSL D3D compiles."""
from pathlib import Path
import argparse
import re
import struct
import subprocess
import tempfile

parser = argparse.ArgumentParser()
parser.add_argument('--dxc', default=r'C:\VulkanSDK\1.4.357.0\Bin\dxc.exe')
parser.add_argument('--validator', default=r'C:\VulkanSDK\1.4.357.0\Bin\spirv-val.exe')
args = parser.parse_args()
root = Path(__file__).resolve().parents[2] / 'runtime/graphics/src/sharpening'
for mode in ('rcas', 'da_rcas', 'da_das'):
    text = (root / (mode + '.h')).read_text()
    hlsl = text.split('R"RSF(', 1)[1].split(')RSF"', 1)[0]
    # Distinct Vulkan bindings for b0,t0,t1,t2,t3,u0.
    hlsl = hlsl.replace('cbuffer Params', '[[vk::binding(0,0)]] cbuffer Params')
    for name, binding in [('Source', 1), ('Motion', 2), ('DepthTex', 3), ('Exposure', 4), ('Dest', 5)]:
        hlsl = re.sub(r'(Texture2D<[^>]+> '+name+r'\s*:)', '[[vk::binding(%d,0)]] ' % binding + r'\1', hlsl) if name != 'Dest' else hlsl.replace('RWTexture2D<float4> Dest', '[[vk::binding(5,0)]] [[vk::image_format("rgba16f")]] RWTexture2D<float4> Dest')
    with tempfile.TemporaryDirectory() as temp:
        src, dst = Path(temp)/'shader.hlsl', Path(temp)/'shader.spv'
        src.write_text(hlsl)
        subprocess.run([args.dxc, '-spirv', '-fspv-target-env=vulkan1.1', '-fvk-use-dx-layout', '-T', 'cs_6_0', '-E', 'CSMain', str(src), '-Fo', str(dst)], check=True)
        subprocess.run([args.validator, '--target-env', 'vulkan1.1', str(dst)], check=True)
        binary = dst.read_bytes()
    words = struct.unpack('<%dI' % (len(binary)//4), binary)
    lines = [', '.join('0x%08xu' % w for w in words[i:i+8]) + ',' for i in range(0,len(words),8)]
    (root/(mode+'_spirv.h')).write_text('// SPDX-License-Identifier: GPL-3.0-only\n// Generated by eng/sharpening/spirv.py from '+mode+'.h.\n// OptiScaler 2fff542; see THIRD_PARTY.md.\n#pragma once\n#include <cstdint>\nnamespace rsf::sharpening {\ninline constexpr uint32_t '+mode+'_spirv[] = {\n'+ '\n'.join(lines)+'\n};\n}\n')
